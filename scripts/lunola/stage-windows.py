"""Stage real Windows x64 inputs, inventory notices, fail closed on collection gaps.

No builds, downloads, signing or publication. --self-test uses actual source
legal files and, if supplied, actual native DLLs; it never fabricates an app.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import struct
import sys
import tempfile
import tomllib

ROOT_LEGAL = ("LICENSE", "LICENSE-EXCEPTIONS.md", "TRADEMARK.md",
              "THIRD_PARTY_NOTICES.md", "CLA.md")
FONT_DIRS = ("src/crates/concat-text/fonts", "src/crates/concat/fonts")
MODEL_DIR = "src/crates/concat-vision/models"
REVIEWS = [
    "Corresponding Source completeness, exact binary/source correspondence and source access",
    "AGPL/GPL, FFmpeg configure flags/source/relinking, codecs and patents",
    "Native archive provenance, sherpa/espeak and Microsoft CRT redistribution terms",
    "Embedded/downloadable model full licenses, NOTICE, attribution and mirror rights",
    "Font provenance, subset internal names, Reserved Font Names and CJK attribution",
    "Resolved target Cargo SBOM, license choices and dependencies without sidecar texts",
    "Lunola artwork/brand rights, upstream attribution and fork contribution/CLA policy",
    "Clean-PATH runtime smoke, dependency closure and installer lifecycle/signature checks",
]


def digest(path: Path) -> str:
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def pe_x64(path: Path) -> None:
    with path.open("rb") as stream:
        if stream.read(2) != b"MZ":
            raise ValueError(f"Not PE: {path}")
        stream.seek(0x3C)
        data = stream.read(4)
        if len(data) != 4:
            raise ValueError(f"Truncated PE: {path}")
        stream.seek(struct.unpack("<I", data)[0])
        if stream.read(4) != b"PE\0\0" or stream.read(2) != b"\x64\x86":
            raise ValueError(f"Not Windows x64 PE: {path}")


def legal_files(root: Path) -> list[Path]:
    """Preserve notice/license directories as well as individually named files."""
    if not root.is_dir():
        return []
    result = []
    for p in sorted(root.rglob("*")):
        if not p.is_file() or p.is_symlink():
            continue
        names = [s.casefold() for s in p.relative_to(root).parts]
        if any(any(s.startswith(w) for w in ("license", "licence", "copying", "notice", "thirdpartynotices", "copyright")) for s in names):
            result.append(p)
    return result


class Collector:
    def __init__(self, stage: Path):
        self.stage = stage
        self.files: dict[str, dict] = {}
        self.gaps: list[str] = []

    def copy(self, src: Path, relative: str) -> None:
        relative = Path(relative).as_posix()
        target = self.stage / relative
        if Path(relative).is_absolute() or ".." in Path(relative).parts:
            raise ValueError(f"Unsafe stage destination: {relative}")
        if not src.is_file() or src.is_symlink():
            raise ValueError(f"Missing/nonregular input: {src}")
        if relative.casefold() in (k.casefold() for k in self.files):
            raise ValueError(f"Duplicate payload filename: {relative}")
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(src, target)
        self.files[relative] = {"sha256": digest(target), "size": target.stat().st_size,
                                "origin": str(src.resolve())}
        if digest(src) != self.files[relative]["sha256"]:
            raise ValueError(f"Input changed during copy: {src}")

    def generated(self, relative: str, text: str) -> None:
        target = self.stage / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8", newline="\n")
        self.files[relative] = {"sha256": digest(target), "size": target.stat().st_size,
                                "origin": "generated by stage-windows.py"}

    def notices(self, root: Path, prefix: str) -> int:
        paths = legal_files(root)
        for path in paths:
            self.copy(path, f"legal/{prefix}/{path.relative_to(root).as_posix()}")
        return len(paths)


def collect_legal(c: Collector, source: Path, tools: dict, registries: list[Path],
                  extra: Path | None, model_license: Path | None) -> dict:
    for name in ROOT_LEGAL:
        c.copy(source / name, name)
    counts = {}
    for relative in FONT_DIRS:
        fonts = source / relative
        paths = sorted(fonts.glob("LICENSE*"))
        if not paths:
            c.gaps.append(f"No actual font licenses: {relative}")
        for path in paths:
            c.copy(path, f"legal/fonts/{Path(relative).parts[2]}/{path.name}")
        counts[relative] = len(paths)
    model = source / MODEL_DIR
    c.copy(model / "NOTICE.md", "legal/models/selfie-segmentation/NOTICE.md")
    counts[MODEL_DIR] = c.notices(model, "models/retained")
    if model_license:
        c.copy(model_license, "legal/models/selfie-segmentation/LICENSE-Apache-2.0.txt")
    else:
        c.gaps.append("Embedded segmentation model full Apache-2.0 text not supplied (--model-license)")
    c.copy(source / "models/manifest.toml", "legal/models/download-manifest.toml")
    for label in ("ffmpeg", "sherpa", "ort", "crt"):
        root = tools.get(label)
        n = c.notices(Path(root), f"native/{label}") if root else 0
        counts[f"native/{label}"] = n
        if not n and label != "crt":
            c.gaps.append(f"No native distribution license/notice material: {label}")
        if label == "ort" and root:
            names = [p.name.casefold() for p in legal_files(Path(root))]
            if not any("thirdpartynotices" in n for n in names):
                c.gaps.append("Actual ONNX Runtime ThirdPartyNotices missing")
        if label == "crt" and root and not n:
            c.gaps.append("CRT DLLs supplied without Microsoft redistribution/license material")
    counts["patches"] = c.notices(source / "src/patches", "patches")
    counts["workspace-crates"] = c.notices(source / "src/crates", "workspace-crates")
    if extra:
        # Reviewed supplemental full texts; never overrides an automatic gap.
        counts["supplemental"] = c.notices(extra, "supplemental")
    lock = tomllib.loads((source / "src/Cargo.lock").read_text(encoding="utf-8"))
    cargo_rows = []
    for pkg in lock["package"]:
        origin = pkg.get("source", "workspace")
        if origin == "workspace":
            continue
        ident = f"{pkg['name']}-{pkg['version']}"
        matches = []
        if origin.startswith("registry+"):
            for registry in registries:
                matches.extend(registry.glob(f"*/{ident}"))
        if len(matches) != 1:
            c.gaps.append(f"Cargo source unavailable/ambiguous for notices: {ident} ({origin})")
            cargo_rows.append({"package": ident, "source": origin, "notices": 0})
            continue
        n = c.notices(matches[0], f"cargo/{ident}")
        manifest = matches[0] / "Cargo.toml"
        metadata = tomllib.loads(manifest.read_text(encoding="utf-8")).get("package", {})
        cargo_rows.append({"package": ident, "source": origin, "notices": n,
                           "declared_license": metadata.get("license"),
                           "declared_license_file": metadata.get("license-file")})
        license_file = metadata.get("license-file")
        if license_file:
            p = (matches[0] / license_file).resolve()
            if not p.is_relative_to(matches[0].resolve()) or not p.is_file():
                c.gaps.append(f"Cargo declared license-file unavailable: {ident}: {license_file}")
            elif p not in legal_files(matches[0]):
                c.copy(p, f"legal/cargo/{ident}/declared-license/{p.name}")
                n += 1
                cargo_rows[-1]["notices"] = n
        if not n:
            c.gaps.append(f"No Cargo full license/notice sidecars: {ident}")
    c.generated("legal/CARGO-LICENSE-INVENTORY.json", json.dumps(cargo_rows, indent=2) + "\n")
    return counts


def native_plan(tools: dict) -> list[Path]:
    """One ORT from Microsoft; never copy sherpa's competing onnxruntime.dll."""
    result = []
    for label in ("ffmpeg", "sherpa", "ort"):
        root = Path(tools[label])
        dlls = sorted(root.rglob("*.dll"))
        if label == "sherpa":
            dlls = [p for p in dlls if p.name.casefold().startswith("sherpa-onnx-")]
        if not dlls:
            raise ValueError(f"No selected DLLs for {label}: {root}")
        if label == "ort" and not any(p.name.casefold() == "onnxruntime.dll" for p in dlls):
            raise ValueError("Microsoft ORT root must include onnxruntime.dll")
        if label == "ffmpeg" and not any(p.name.casefold().startswith("avcodec-") for p in dlls):
            raise ValueError("FFmpeg root must contain shared avcodec DLL")
        result.extend(dlls)
    if tools.get("crt"):
        result.extend(sorted(Path(tools["crt"]).rglob("*.dll")))
    seen = set()
    for p in result:
        key = p.name.casefold()
        if key in seen:
            raise ValueError(f"Conflicting duplicate DLL: {p.name}")
        seen.add(key)
        pe_x64(p)
    return result


def verify_inventory(stage: Path, files: dict, extra: set[str] | None = None) -> None:
    actual = {p.relative_to(stage).as_posix() for p in stage.rglob("*") if p.is_file()}
    expected = set(files) | (extra or set())
    if actual != expected:
        raise ValueError(f"Stage inventory mismatch: missing={expected-actual}; extra={actual-expected}")
    if any(p.is_symlink() for p in stage.rglob("*")):
        raise ValueError("Stage contains symlinks")
    for name, info in files.items():
        relative = Path(name)
        if relative.is_absolute() or ".." in relative.parts:
            raise ValueError(f"Unsafe manifest path: {name}")
        p = stage / relative
        if p.stat().st_size != info["size"] or digest(p) != info["sha256"]:
            raise ValueError(f"Stage digest/size mismatch: {name}")
        if p.suffix.casefold() in (".dll", ".exe"):
            pe_x64(p)


def verify(stage: Path, allow_incomplete: bool = False) -> dict:
    manifest = json.loads((stage / "STAGE-MANIFEST.json").read_text(encoding="utf-8"))
    verify_inventory(stage, manifest["files"], {"STAGE-MANIFEST.json"})
    for required in (*ROOT_LEGAL, "lunola-mova.exe", "lunola-mova.ico", "SOURCE-README.md",
                     "onnxruntime.dll", "legal/models/selfie-segmentation/NOTICE.md"):
        if required not in manifest["files"]:
            raise ValueError(f"Required staged file missing: {required}")
    if manifest["collection_gaps"] and not allow_incomplete:
        raise ValueError("Incomplete legal/source collection; inspect STAGE-MANIFEST.json")
    return manifest


def self_test(source: Path, tools: dict | None, registries: list[Path]) -> None:
    with tempfile.TemporaryDirectory(prefix="mova-stage-test-", dir=os.environ.get("TMPDIR")) as tmp:
        c = Collector(Path(tmp))
        counts = collect_legal(c, source, tools or {}, registries, None, None)
        for name in ROOT_LEGAL:
            assert (c.stage / name).read_bytes() == (source / name).read_bytes()
        for relative in FONT_DIRS:
            assert counts[relative] == len(list((source / relative).glob("LICENSE*"))) > 0
        for relative, info in c.files.items():
            assert digest(c.stage / relative) == info["sha256"]
        assert any("model full Apache" in gap for gap in c.gaps)
        verify_inventory(c.stage, c.files)
        staged_license = c.stage / "LICENSE"
        original = staged_license.read_bytes()
        staged_license.write_bytes(original + b"\n")
        try:
            verify_inventory(c.stage, c.files)
        except ValueError as error:
            assert "digest/size" in str(error)
        else:
            raise AssertionError("Altered legal payload accepted")
        staged_license.write_bytes(original)
        unexpected = c.stage / "UNEXPECTED-LICENSE"
        shutil.copyfile(source / "LICENSE", unexpected)
        try:
            verify_inventory(c.stage, c.files)
        except ValueError as error:
            assert "extra=" in str(error)
        else:
            raise AssertionError("Uninventoried payload accepted")
        unexpected.unlink()
        staged_license.unlink()
        try:
            verify_inventory(c.stage, c.files)
        except ValueError as error:
            assert "missing=" in str(error)
        else:
            raise AssertionError("Missing legal payload accepted")
        shutil.copyfile(source / "LICENSE", staged_license)
        verify_inventory(c.stage, c.files)
        try:
            c.copy(source / "LICENSE", "license")
        except ValueError:
            pass
        else:
            raise AssertionError("Case-insensitive collision accepted")
        try:
            pe_x64(source / "LICENSE")
        except ValueError:
            pass
        else:
            raise AssertionError("Non-PE legal text accepted as x64 executable")
        native_count = len(native_plan(tools)) if tools else 0
        if tools:
            plan = native_plan(tools)
            assert sum(p.name.casefold() == "onnxruntime.dll" for p in plan) == 1
            assert all(not p.name.casefold().startswith("onnxruntime") for p in plan
                       if p.is_relative_to(Path(tools["sherpa"])))
            duplicate_tools = dict(tools, crt=tools["ort"])
            try:
                native_plan(duplicate_tools)
            except ValueError as error:
                assert "duplicate" in str(error)
            else:
                raise AssertionError("Conflicting ORT DLLs accepted")
        print(json.dumps({"self_test": "PASS", "actual_legal_files": len(c.files),
                          "font_license_counts": {p: counts[p] for p in FONT_DIRS},
                          "actual_x64_native_dlls_checked": native_count,
                          "collection_gaps_detected": len(c.gaps),
                          "app_or_installer_built": False}, indent=2))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, help="Source checkout root")
    parser.add_argument("--exe", type=Path, help="Built, smoke-tested Lunola Mova x64 executable")
    parser.add_argument("--tools", type=Path, help="JSON: ffmpeg/sherpa/ort distribution roots, optional crt root")
    parser.add_argument("--stage", type=Path, help="New output directory (never overwrite)")
    parser.add_argument("--version", help="Actual build version")
    parser.add_argument("--revision", help="Exact build source revision/label, including dirty-source identity")
    parser.add_argument("--source-archive", type=Path, help="Reviewed matching Corresponding Source archive")
    parser.add_argument("--model-license", type=Path, help="Actual full Apache-2.0 license for embedded model")
    parser.add_argument("--cargo-registry", type=Path, action="append", default=[], help="Cargo registry/src root")
    parser.add_argument("--extra-legal", type=Path, help="Supplemental reviewed license/notice tree")
    parser.add_argument("--allow-incomplete-legal", action="store_true", help="DRAFT ONLY: retain/report collection gaps")
    parser.add_argument("--verify", type=Path, metavar="STAGE", help="Verify existing inventory without staging")
    parser.add_argument("--self-test", action="store_true", help="Test collectors against actual supplied files")
    args = parser.parse_args()
    if args.verify:
        m = verify(args.verify, args.allow_incomplete_legal)
        print(f"Inventory verified: {len(m['files'])} files; legal clearance and runtime checks NOT asserted")
        return 0
    if not args.source:
        parser.error("--source required for staging/self-test")
    tools = json.loads(args.tools.read_text(encoding="utf-8")) if args.tools else None
    if tools:
        for label in ("ffmpeg", "sherpa", "ort"):
            if label not in tools or not Path(tools[label]).is_absolute() or not Path(tools[label]).is_dir():
                parser.error(f"--tools requires existing absolute distribution root: {label}")
        if tools.get("crt") and (not Path(tools["crt"]).is_absolute() or not Path(tools["crt"]).is_dir()):
            parser.error("crt must be an existing absolute directory")
    if args.self_test:
        self_test(args.source, tools, args.cargo_registry)
        return 0
    if not all((args.exe, tools, args.stage, args.version, args.revision)):
        parser.error("staging requires --exe --tools --source --stage --version --revision")
    stage = args.stage.resolve()
    inputs = [args.source.resolve(), args.exe.resolve().parent,
              *[Path(v).resolve() for v in tools.values() if isinstance(v, str)]]
    for p in (args.source_archive, args.model_license, args.extra_legal):
        if p:
            inputs.append(p.resolve() if p.is_dir() else p.resolve().parent)
    if any(stage == p or p.is_relative_to(stage) or stage.is_relative_to(p) for p in inputs):
        raise ValueError("Stage overlaps input paths; choose a separate new output directory")
    if stage.exists():
        raise ValueError("Stage already exists; use a fresh directory (no destructive cleanup)")
    if args.exe.name.casefold() != "lunola-mova.exe":
        raise ValueError("Expected built lunola-mova.exe; do not stage the upstream baseline as the fork")
    pe_x64(args.exe)
    dlls = native_plan(tools)
    icon = args.source / "assets/lunola/lunola-mova.ico"
    if not icon.is_file():
        raise ValueError("Native Lunola icon missing; integrate supplied assets first")
    stage.mkdir(parents=True)
    c = Collector(stage)
    c.copy(args.exe, "lunola-mova.exe")
    c.copy(icon, "lunola-mova.ico")
    for dll in dlls:
        c.copy(dll, dll.name)
    counts = collect_legal(c, args.source, tools, args.cargo_registry,
                           args.extra_legal, args.model_license)
    archive_name = None
    if args.source_archive:
        archive_name = f"source/{args.source_archive.name}"
        c.copy(args.source_archive, archive_name)
    else:
        c.gaps.append("Matching Corresponding Source archive missing (--source-archive)")
    c.generated("SOURCE-README.md", f"""# Lunola Mova — source access

Version: {args.version}
Build source identity supplied by distributor: {args.revision}
Bundled Corresponding Source: {archive_name or 'MISSING — DRAFT, DO NOT DISTRIBUTE'}

Retain Jareer and Concat contributors and all third-party copyrights.
See LICENSE, LICENSE-EXCEPTIONS.md, TRADEMARK.md and THIRD_PARTY_NOTICES.md.
The distributor must verify this archive matches the exact binary and includes
fork changes, build/control scripts and relevant dependency source/patches.
An upstream link or this README alone does not satisfy source-access obligations.
No official Lunola source website or written-offer destination is invented here.
For online releases provide equivalent reviewed source access with the binary;
remote API operation also needs source-offer review. See STAGE-MANIFEST.json for
collection gaps and unresolved legal/runtime review gates. A digest is not legal
clearance, nor proof that Corresponding Source is complete.
""")
    manifest = {"product": "Lunola Mova", "publisher_metadata": "Lunola", "arch": "x64",
                "version": args.version, "source_identity": args.revision,
                "status": "draft-staged-not-release-approved", "files": c.files,
                "legal_counts": counts, "collection_gaps": c.gaps,
                "unresolved_review_gates": REVIEWS}
    (stage / "STAGE-MANIFEST.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    verify(stage, args.allow_incomplete_legal)
    print(f"Staged and inventoried {len(c.files)} files. Not built/smoked/legally cleared by this helper.")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (ValueError, OSError, KeyError, tomllib.TOMLDecodeError, json.JSONDecodeError) as exc:
        print(f"STAGING BLOCKED: {exc}", file=sys.stderr)
        raise SystemExit(1)
